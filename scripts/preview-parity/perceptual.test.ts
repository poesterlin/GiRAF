test('CIEDE2000 matches every Sharma pair to published rounding, in both directions', () => {
	for (const [l1, a1, b1, l2, a2, b2, expected] of pairs) {
		const a: Lab = [l1, a1, b1],
			b: Lab = [l2, a2, b2];
		expect(Math.abs(deltaE00(a, b) - expected)).toBeLessThan(0.00005);
		expect(Math.abs(deltaE00(b, a) - expected)).toBeLessThan(0.00005);
		expect(deltaE00(a, a)).toBe(0);
	}
});
test('sRGB transfer and D65 Lab match reference primaries and neutrals', () => {
	const samples = [
		[0, 0, 0, 0, 0, 0],
		[255, 255, 255, 100, 0, 0],
		[255, 0, 0, 53.2408, 80.0925, 67.2032],
		[0, 255, 0, 87.7347, -86.1827, 83.1793],
		[0, 0, 255, 32.297, 79.1875, -107.8602],
		[128, 128, 128, 53.585, 0, 0],
		[10, 10, 10, 2.7417, 0, 0],
		[11, 11, 11, 3.0229, 0, 0]
	];
	for (const [r, g, b, l, a, bb] of samples) {
		const lab = rgbToLab(r, g, b);
		[l, a, bb].forEach((v, i) => expect(lab[i]).toBeCloseTo(v, 3));
	}
	expect(deltaE00(rgbToLab(0, 0, 0), rgbToLab(255, 255, 255))).toBeCloseTo(100, 4);
});
